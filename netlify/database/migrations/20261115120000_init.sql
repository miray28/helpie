-- Helpie schema. Applied automatically by Netlify on every deploy, and by the
-- app itself when it runs against the embedded local database.
-- All timestamps are bigint milliseconds since the Unix epoch.

create table if not exists users (
  id              integer generated by default as identity primary key,
  username        text not null,
  email           text not null,
  password_hash   text not null,
  role            text not null default 'donor' check (role in ('donor','recipient','admin')),
  about           text,
  phone           text,
  address         text,
  profile_image   text,
  cover_image     text,
  verified        integer not null default 0,
  profile_visible integer not null default 1,
  blocked         integer not null default 0,
  created_at      bigint not null,
  last_login      bigint
);
create unique index if not exists users_username_key on users (lower(username));
create unique index if not exists users_email_key on users (lower(email));

create table if not exists categories (
  id          integer generated by default as identity primary key,
  name        text not null,
  description text
);
create unique index if not exists categories_name_key on categories (lower(name));

create table if not exists posts (
  id              integer generated by default as identity primary key,
  user_id         integer not null references users(id) on delete cascade,
  type            text not null check (type in ('donation','request')),
  title           text not null,
  content         text not null,
  category_id     integer references categories(id) on delete set null,
  condition_state text check (condition_state in ('new','like_new','good','fair')),
  quantity        integer,
  expiry_date     text,
  location        text,
  image           text,
  status          text not null default 'available' check (status in ('available','pending','claimed')),
  created_at      bigint not null,
  updated_at      bigint not null
);
create index if not exists posts_created on posts (created_at desc);
create index if not exists posts_user on posts (user_id);
create index if not exists posts_category on posts (category_id);

create table if not exists comments (
  id         integer generated by default as identity primary key,
  post_id    integer not null references posts(id) on delete cascade,
  user_id    integer not null references users(id) on delete cascade,
  content    text not null,
  created_at bigint not null
);
create index if not exists comments_post on comments (post_id);
create index if not exists comments_user on comments (user_id);

create table if not exists saved_posts (
  user_id  integer not null references users(id) on delete cascade,
  post_id  integer not null references posts(id) on delete cascade,
  saved_at bigint not null,
  primary key (user_id, post_id)
);
create index if not exists saved_posts_post on saved_posts (post_id);

create table if not exists donation_requests (
  id           integer generated by default as identity primary key,
  post_id      integer not null references posts(id) on delete cascade,
  requester_id integer not null references users(id) on delete cascade,
  notes        text,
  status       text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at   bigint not null,
  unique (post_id, requester_id)
);
create index if not exists donation_requests_requester on donation_requests (requester_id);

create table if not exists conversations (
  id         integer generated by default as identity primary key,
  user1_id   integer not null references users(id) on delete cascade,
  user2_id   integer not null references users(id) on delete cascade,
  updated_at bigint not null,
  unique (user1_id, user2_id),
  check (user1_id < user2_id)
);
create index if not exists conversations_user2 on conversations (user2_id);

create table if not exists messages (
  id              integer generated by default as identity primary key,
  conversation_id integer not null references conversations(id) on delete cascade,
  sender_id       integer not null references users(id) on delete cascade,
  body            text not null,
  created_at      bigint not null,
  read_at         bigint
);
create index if not exists messages_conversation on messages (conversation_id, id);
create index if not exists messages_sender on messages (sender_id);

create table if not exists reports (
  id               integer generated by default as identity primary key,
  content_type     text not null check (content_type in ('post','comment','user')),
  content_id       integer not null,
  reporter_id      integer references users(id) on delete set null,
  reported_user_id integer references users(id) on delete cascade,
  type             text not null check (type in ('spam','inappropriate','harassment','other')),
  reason           text,
  status           text not null default 'pending' check (status in ('pending','resolved','dismissed')),
  action_taken     text,
  resolved_by      integer references users(id) on delete set null,
  resolved_at      bigint,
  created_at       bigint not null
);
create index if not exists reports_status on reports (status, created_at desc);
create index if not exists reports_reporter on reports (reporter_id);
create index if not exists reports_reported on reports (reported_user_id);
create index if not exists reports_resolved_by on reports (resolved_by);

create table if not exists contact_messages (
  id         integer generated by default as identity primary key,
  name       text not null,
  email      text not null,
  subject    text not null,
  message    text not null,
  created_at bigint not null
);

create table if not exists settings (
  key   text primary key,
  value text not null
);

create table if not exists sessions (
  sid     text primary key,
  user_id integer,
  data    text not null,
  expires bigint not null
);
create index if not exists sessions_user on sessions (user_id);
create index if not exists sessions_expires on sessions (expires);

create table if not exists rate_limits (
  key     text primary key,
  count   integer not null,
  expires bigint not null
);

